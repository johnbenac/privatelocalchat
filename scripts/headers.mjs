// The headers a host must send for the app to work, written once (docs/RUN-IT.md).
//
// The build writes `_headers` from these rules (Cloudflare Pages' file; Netlify and others read the same format), `scripts/serve.mjs` applies the `_headers` of the folder it serves, and
//   node scripts/headers.mjs pages|nginx|caddy
// prints the same rules for a host that is configured by hand. There is no second list to drift.
//
// Why they matter:
// - Cross-Origin-Opener-Policy and Cross-Origin-Embedder-Policy make the page cross-origin isolated, which the on-device model threads need.
// - sw.js, build-info.js and version.json must never be answered from a cache: they are how a copy finds out that a newer build exists.
import {fileURLToPath} from 'node:url';

export const HEADER_RULES = Object.freeze([
  {path: '/*', headers: [
    ['Cross-Origin-Opener-Policy', 'same-origin'],
    ['Cross-Origin-Embedder-Policy', 'require-corp'],
    ['X-Content-Type-Options', 'nosniff'],
    ['Referrer-Policy', 'strict-origin-when-cross-origin']
  ]},
  {path: '/sw.js', headers: [['Cache-Control', 'no-cache']]},
  {path: '/build-info.js', headers: [['Cache-Control', 'no-cache']]},
  {path: '/version.json', headers: [['Cache-Control', 'no-cache']]},
  {path: '/sitemap.xml', headers: [['Cache-Control', 'public, max-age=3600']]},
  {path: '/updates/rss.xml', headers: [['Cache-Control', 'public, max-age=3600']]},
  {path: '/LICENSE', headers: [['Content-Type', 'text/plain; charset=utf-8'], ['Cache-Control', 'public, max-age=3600']]},
  {path: '/THIRD-PARTY-NOTICES.md', headers: [['Content-Type', 'text/markdown; charset=utf-8'], ['Cache-Control', 'public, max-age=3600']]}
]);

/** The rules in the `_headers` file format. */
export const toPagesHeaders = (rules = HEADER_RULES) =>
  rules.map((r) => r.path + '\n' + r.headers.map(([k, v]) => '  ' + k + ': ' + v + '\n').join('')).join('\n');

/** Reads a `_headers` file back into rules: a path line, then indented `Name: value` lines. Lines starting with # are comments. */
export function parsePagesHeaders(text) {
  const rules = [];
  let current = null;
  for (const raw of String(text).split(/\r?\n/)) {
    if (!raw.trim() || raw.trim().startsWith('#')) continue;
    if (/^\s/.test(raw)) {
      const m = /^\s+([^:\s][^:]*):\s*(.*)$/.exec(raw);
      if (!m || !current) throw new Error('A line of _headers is not a header: ' + raw.trim());
      current.headers.push([m[1].trim(), m[2].trim()]);
    } else { current = {path: raw.trim(), headers: []}; rules.push(current); }
  }
  return rules;
}

const escapeRegExp = (s) => s.replace(/[.+?^${}()|[\]\\]/g, '\\$&');
/** Whether a rule's path matches a request path: `*` is a splat, anything else is exact. */
export const ruleMatches = (rulePath, pathname) => new RegExp('^' + rulePath.split('*').map(escapeRegExp).join('.*') + '$').test(pathname);

/** The headers for a request path: every matching rule, in order, a later value replacing an earlier one of the same name. */
export function headersFor(rules, pathname) {
  const out = new Map();
  for (const rule of rules) if (ruleMatches(rule.path, pathname)) for (const [k, v] of rule.headers) out.set(k.toLowerCase(), [k, v]);
  return Object.fromEntries([...out.values()]);
}

// ---- other servers ------------------------------------------------------------------------------------------------------------------------------
const baseOf = (rules) => rules.find((r) => r.path === '/*')?.headers ?? [];
const q = (v) => '"' + String(v).replace(/(["\\])/g, '\\$1') + '"';

/** nginx: inside a server block. add_header in a location replaces the inherited ones, so each location repeats the shared headers. */
export function toNginx(rules = HEADER_RULES) {
  const base = baseOf(rules);
  const lines = ['# Generated by node scripts/headers.mjs nginx: the headers the app needs (docs/RUN-IT.md). Put it inside the server block that serves the app.'];
  for (const [k, v] of base) lines.push(`add_header ${k} ${q(v)} always;`);
  for (const rule of rules) {
    if (rule.path === '/*') continue;
    lines.push('', `location = ${rule.path} {`);
    for (const [k, v] of base) lines.push(`  add_header ${k} ${q(v)} always;`);
    for (const [k, v] of rule.headers) {
      if (k.toLowerCase() === 'content-type') { const [type, ...rest] = v.split(/;\s*/); lines.push(`  default_type ${type};`); const charset = rest.find((x) => /^charset=/i.test(x)); if (charset) lines.push(`  charset ${charset.split('=')[1]};`); }
      else lines.push(`  add_header ${k} ${q(v)} always;`);
    }
    lines.push('}');
  }
  return lines.join('\n') + '\n';
}

/** Caddy: inside a site block. */
export function toCaddy(rules = HEADER_RULES) {
  const lines = ['# Generated by node scripts/headers.mjs caddy: the headers the app needs (docs/RUN-IT.md). Put it inside the site block that serves the app.', 'header {'];
  for (const [k, v] of baseOf(rules)) lines.push(`  ${k} ${q(v)}`);
  lines.push('}');
  rules.filter((r) => r.path !== '/*').forEach((rule, i) => {
    lines.push('', `@rule${i + 1} path ${rule.path}`, `header @rule${i + 1} {`);
    for (const [k, v] of rule.headers) lines.push(`  ${k} ${q(v)}`);
    lines.push('}');
  });
  return lines.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const format = process.argv[2];
  const out = {pages: toPagesHeaders, nginx: toNginx, caddy: toCaddy}[format];
  if (!out) { console.error('Usage: node scripts/headers.mjs pages|nginx|caddy'); process.exit(2); }
  process.stdout.write(out());
}
