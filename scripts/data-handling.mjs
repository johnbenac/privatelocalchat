#!/usr/bin/env node
// Keeps the two generated tables of docs/DATA-HANDLING.md equal to the two inventories they come from.
//
//   node scripts/data-handling.mjs write    rewrite the text between the markers; every other byte of the document stays
//   node scripts/data-handling.mjs check    exit 1 and show the first differences if the document and the inventories disagree
//
// Options for both verbs: --doc FILE, --storage FILE, --network FILE (tests use temporary copies).
// Exit codes: 0 current, 1 differs, 2 usage or refusal. A refusal changes nothing.
import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DEFAULTS = {
  doc: path.join(ROOT, 'docs/DATA-HANDLING.md'),
  storage: path.join(ROOT, 'docs/evidence/encryption/storage-inventory.json'),
  network: path.join(ROOT, 'docs/evidence/split/network-origins.json')
};
export const BLOCKS = ['storage', 'hosts'];
export const marker = (name, edge) => '<!-- data-handling:' + name + ':' + edge + ' -->';
const SHOW_DIFFERENCES = 8;

/** A problem the person can fix; the command line prints its message and exits 2. */
export class Refusal extends Error {}

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0); // code-point order, not locale order
const cell = (value) => String(value).replace(/\r?\n|\r/g, ' ').replace(/\|/g, '\\|');
const row = (...cells) => '| ' + cells.map(cell).join(' | ') + ' |';
const table = (head, rows) => [row(...head), row(...head.map(() => '---')), ...rows.map((r) => row(...r))].join('\n');
const code = (value) => '`' + String(value).replace(/`/g, "'") + '`';
const GENERATED = (name) => '<!-- Generated by `node scripts/data-handling.mjs write` from ' + name + '. Do not edit by hand. -->';

function need(ok, what, file) {
  if (!ok) throw new Refusal('The inventory ' + file + ' lacks ' + what + '. Restore it from git, or fix the field, then run the command again.');
}
const isText = (v) => typeof v === 'string' && v !== '';
const isObject = (v) => v && typeof v === 'object' && !Array.isArray(v);

function validateStorage(s, file) {
  need(isObject(s), 'a JSON object at the top', file);
  need(isObject(s.classes), 'the field "classes"', file);
  for (const list of ['keys', 'databases', 'deviceStores']) need(Array.isArray(s[list]), 'the field "' + list + '"', file);
  need(isObject(s.files) && Array.isArray(s.files.list), 'the field "files.list"', file);
  const fields = {keys: ['key', 'store', 'class', 'note', 'format', 'since'], databases: ['name', 'store', 'class', 'note', 'format', 'since'], deviceStores: ['name', 'class', 'owner']};
  for (const [list, names] of Object.entries(fields)) {
    s[list].forEach((item, i) => {
      need(isObject(item), 'an object at ' + list + '[' + i + ']', file);
      for (const f of names) need(item[f] !== undefined && item[f] !== null && item[f] !== '', 'the field "' + list + '[' + i + '].' + f + '"', file);
      need(isText(s.classes[item.class]), 'a description in "classes" for the class "' + item.class + '" (used by ' + list + '[' + i + '])', file);
    });
  }
}

function validateNetwork(n, file) {
  need(isObject(n), 'a JSON object at the top', file);
  for (const section of ['appHosts', 'vendorHosts', 'ownFetchPaths']) {
    need(isObject(n[section]), 'the field "' + section + '"', file);
    for (const [k, files] of Object.entries(n[section])) need(Array.isArray(files), 'a list of files at "' + section + '.' + k + '"', file);
  }
}

/** The two generated blocks, each ending with a newline, from the parsed inventories. */
export function generate(storage, network) {
  const byKey = (list, field) => [...list].sort((a, b) => cmp(a[field], b[field]) || cmp(a.owner || '', b.owner || ''));
  const keys = byKey(storage.keys, 'key'), databases = byKey(storage.databases, 'name'), devices = byKey(storage.deviceStores, 'name');
  const used = [...new Set([...keys, ...databases, ...devices].map((i) => i.class))].sort(cmp);
  const where = (store) => (store === 'localStorage' ? 'local storage' : store === 'sessionStorage' ? 'session storage' : store);
  const out = [GENERATED('docs/evidence/encryption/storage-inventory.json'), ''];
  out.push(table(['Class', 'What it means'], used.map((c) => [code(c), storage.classes[c]])), '');
  out.push('**Keys in local and session storage (' + keys.length + ')**', '');
  out.push(table(['Key', 'Where', 'Class', 'What it holds', 'Format', 'First release'],
    keys.map((k) => [code(k.key), where(k.store), code(k.class), k.note, k.format, k.since])), '');
  out.push('**Databases (' + databases.length + ')**', '');
  out.push(table(['Name', 'Where', 'Class', 'What it holds', 'Format', 'First release'],
    databases.map((d) => [code(d.name), d.store, code(d.class), d.note, d.format, d.since])), '');
  out.push('**Device stores (' + devices.length + ')**', '');
  out.push(table(['Name', 'Class', 'Written by'], devices.map((d) => [d.name, code(d.class), d.owner])), '');
  out.push(storage.files.list.length + ' source files read or write browser storage; the list is in `files.list` of docs/evidence/encryption/storage-inventory.json.');
  const storageBlock = out.join('\n') + '\n';

  const fileList = (files) => [...files].sort(cmp).map(code).join(', ');
  const hostRows = (bucket) => Object.keys(bucket).sort(cmp).map((h) => [code(h), fileList(bucket[h])]);
  const o = [GENERATED('docs/evidence/split/network-origins.json'), ''];
  o.push('A host named in the source is not a host the app contacts: the provider list and the documentation links name hosts that are only used when a person chooses them.', '');
  o.push('**Hosts named by the app\'s own files (' + Object.keys(network.appHosts).length + ')**', '');
  o.push(table(['Host', 'Files that name it'], hostRows(network.appHosts)), '');
  o.push('**Hosts named only inside vendored libraries (' + Object.keys(network.vendorHosts).length + ')**', '');
  o.push(table(['Host', 'Files that name it'], hostRows(network.vendorHosts)), '');
  o.push('**Paths the app fetches from its own origin (' + Object.keys(network.ownFetchPaths).length + ')**', '');
  o.push(table(['Path', 'Files that fetch it'], hostRows(network.ownFetchPaths)));
  return {storage: storageBlock, hosts: o.join('\n') + '\n'};
}

/** Find the content between each pair of markers; refuse when the markers are not exactly one clean pair each. */
function locate(doc, file) {
  const spans = {};
  let last = -1;
  for (const name of BLOCKS) {
    const [start, end] = ['start', 'end'].map((edge) => marker(name, edge));
    const at = (needle) => { const all = []; for (let i = doc.indexOf(needle); i !== -1; i = doc.indexOf(needle, i + 1)) all.push(i); return all; };
    const [s, e] = [at(start), at(end)];
    for (const [m, found] of [[start, s], [end, e]]) {
      if (found.length === 0) throw new Refusal(file + ' has no line ' + m + '. Add it on a line of its own where the generated table belongs.');
      if (found.length > 1) throw new Refusal(file + ' has the line ' + m + ' ' + found.length + ' times. Keep exactly one.');
      const lineStart = found[0] === 0 || doc[found[0] - 1] === '\n', lineEnd = doc[found[0] + m.length] === undefined || doc[found[0] + m.length] === '\n';
      if (!lineStart || !lineEnd) throw new Refusal('In ' + file + ' the marker ' + m + ' must be on a line of its own.');
    }
    if (e[0] < s[0]) throw new Refusal('In ' + file + ' the end marker of "' + name + '" comes before its start marker. Put ' + start + ' first.');
    if (s[0] < last) throw new Refusal('In ' + file + ' the "' + name + '" block is out of order: the blocks go ' + BLOCKS.join(', ') + '.');
    last = e[0];
    spans[name] = {from: s[0] + start.length + 1, to: e[0]};
  }
  return spans;
}

/** The document with both blocks replaced by `blocks`. */
export function apply(doc, blocks, file = 'the document') {
  const spans = locate(doc, file);
  let out = doc;
  for (const name of [...BLOCKS].reverse()) out = out.slice(0, spans[name].from) + blocks[name] + out.slice(spans[name].to);
  return out;
}

async function readJson(file, what) {
  let text;
  try { text = await readFile(file, 'utf8'); } catch { throw new Refusal('The ' + what + ' inventory ' + file + ' cannot be read. Check the path given to --' + (what === 'storage' ? 'storage' : 'network') + '.'); }
  try { return JSON.parse(text); } catch (error) { throw new Refusal('The ' + what + ' inventory ' + file + ' is not valid JSON (' + error.message + '). Restore it from git.'); }
}

async function load(options) {
  let doc;
  try { doc = await readFile(options.doc, 'utf8'); } catch { throw new Refusal('The document ' + options.doc + ' does not exist or cannot be read. Check the path given to --doc.'); }
  const storage = await readJson(options.storage, 'storage'), network = await readJson(options.network, 'network');
  validateStorage(storage, options.storage);
  validateNetwork(network, options.network);
  const blocks = generate(storage, network);
  return {doc, next: apply(doc, blocks, options.doc), blocks};
}

/** Lines that differ between two texts, as readable lines (the first few only). */
function differences(before, after) {
  const a = before.split('\n'), b = after.split('\n'), found = [];
  let total = 0;
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] === b[i]) continue;
    total++;
    if (found.length < SHOW_DIFFERENCES) found.push('line ' + (i + 1) + '\n  document: ' + (a[i] ?? '(missing)') + '\n  expected: ' + (b[i] ?? '(missing)'));
  }
  return {total, shown: found};
}

export function parseArgs(argv) {
  const [command, ...rest] = argv;
  const options = {...DEFAULTS};
  for (let i = 0; i < rest.length; i += 2) {
    const flag = rest[i];
    if (!['--doc', '--storage', '--network'].includes(flag) || rest[i + 1] === undefined) throw new Refusal('Unknown or incomplete option ' + flag + '. Usage: data-handling.mjs write|check [--doc FILE] [--storage FILE] [--network FILE]');
    options[flag.slice(2)] = path.resolve(rest[i + 1]);
  }
  return {command, options};
}

export async function cli(argv, log = console.log) {
  try {
    const {command, options} = parseArgs(argv);
    if (command !== 'write' && command !== 'check') throw new Refusal('Usage: data-handling.mjs write|check [--doc FILE] [--storage FILE] [--network FILE]');
    const {doc, next} = await load(options);
    if (command === 'write') {
      if (next !== doc) await writeFile(options.doc, next);
      log((next === doc ? 'Unchanged: ' : 'Wrote ') + options.doc);
      return 0;
    }
    if (next === doc) { log('The generated tables of ' + options.doc + ' are current.'); return 0; }
    const d = differences(doc, next);
    log('The generated tables of ' + options.doc + ' differ from the inventories (' + d.total + ' lines):\n' + d.shown.join('\n') +
      (d.total > d.shown.length ? '\n... and ' + (d.total - d.shown.length) + ' more' : '') + '\nIf this change is intended, run: node scripts/data-handling.mjs write');
    return 1;
  } catch (error) {
    if (!(error instanceof Refusal)) throw error;
    console.error(error.message);
    return 2;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exitCode = await cli(process.argv.slice(2));
